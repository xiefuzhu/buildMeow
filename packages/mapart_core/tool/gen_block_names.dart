// Builds `assets/lang/zh_cn_blocks.json` — the block-id -> Chinese name table
// the interface and the blueprint sheets label blocks with.
//
// The names come from Minecraft's own language file, not from a hand-typed
// list, so they are the names the game itself shows. The export files keep
// using the English block ids either way; only what is printed changes.
//
// Usage, from the mapart_core package root:
//   dart run tool/gen_block_names.dart [path/to/zh_cn.json]
//
// The default input is `tool/data/zh_cn_26_1_2.json`, vendored from
// InventivetalentDev/minecraft-assets. See `assets/lang/NOTICE.md`.
import 'dart:convert';
import 'dart:io';

import 'package:mapart_core/mapart_core.dart';

/// Keys in the language file look like `block.minecraft.white_concrete`.
/// Anything after the second dot belongs to a sub-entry (a sign variant, a
/// potted plant), so only ids without a further dot are block names.
const String _prefix = 'block.minecraft.';

/// The release the vendored tables target, and so the one the palette is
/// checked against.
const String defaultVersion = '26.1.2';

void main(List<String> args) {
  final input = File(
    args.isNotEmpty ? args[0] : 'tool/data/zh_cn_26_1_2.json',
  );
  if (!input.existsSync()) {
    stderr.writeln('missing ${input.path}');
    exitCode = 1;
    return;
  }

  final raw = jsonDecode(input.readAsStringSync()) as Map<String, dynamic>;
  final names = <String, String>{};
  var skipped = 0;
  for (final entry in raw.entries) {
    if (!entry.key.startsWith(_prefix)) continue;
    final id = entry.key.substring(_prefix.length);
    // A potted plant is `block.minecraft.potted_oak_sapling` and is a block of
    // its own, but a sign's front text is `block.minecraft.oak_sign.front_text`
    // and is not. Ids never contain a dot, so anything with one is a sub-entry.
    if (id.contains('.') || id.isEmpty) {
      skipped++;
      continue;
    }
    names[id] = entry.value as String;
  }

  final sorted = Map.fromEntries(
    names.entries.toList()..sort((a, b) => a.key.compareTo(b.key)),
  );

  final out = File('assets/lang/zh_cn_blocks.json');
  out.parent.createSync(recursive: true);
  out.writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert({
      'schemaVersion': 1,
      'note':
          'Block id -> Simplified Chinese name, taken from Minecraft\'s own '
          'zh_cn language file. Generated by tool/gen_block_names.dart; do not '
          'hand-edit. Provenance and licence: assets/lang/NOTICE.md.',
      'blocks': sorted,
    })}\n',
  );

  final missing = _missingNames(names.keys.toSet());
  stdout.writeln(
    'wrote ${sorted.length} names to ${out.path} '
    '(skipped $skipped sub-entries, ${raw.length} keys read)',
  );
  if (missing.isEmpty) {
    stdout.writeln('every block the palette can offer has a Chinese name');
  } else {
    stdout.writeln(
      '${missing.length} blocks the palette can offer have no Chinese name '
      'and will fall back to their English one:',
    );
    for (final id in missing) {
      stdout.writeln('  $id');
    }
  }
}

/// Block ids the app can actually put on the map: every block of the palette
/// it builds for the release the vendored tables target. Used only to report
/// coverage — a missing name is not an error, because the palette falls back to
/// the English display name.
List<String> _missingNames(Set<String> known) {
  final ids = _paletteBlockIds();
  final missing = ids.where((id) => !known.contains(id)).toList()..sort();
  return missing;
}

/// The ids of every palette entry for `26.1.2` with the support-requiring
/// blocks admitted, which is the widest the palette ever gets. Built through
/// the real `Palette` and the real block-colour filter rather than by reading
/// the JSON by hand, so a name that is missing only because of a table the app
/// does not actually use cannot hide here.
Set<String> _paletteBlockIds() {
  final colors = jsonDecode(
    File('assets/colors/mapartcraft.colors.json').readAsStringSync(),
  );
  final catalog = jsonDecode(
    File('assets/colors/block_map_colors.json').readAsStringSync(),
  );
  final blockColors = jsonDecode(
    File('assets/colors/texture_palette_26_1_2.json').readAsStringSync(),
  );
  final versions = VersionTable.fromJson(
    jsonDecode(File('assets/colors/versions.json').readAsStringSync())
        as Map<String, dynamic>,
  );

  final table = ColorTable.fromJson(colors as Map<String, dynamic>)
      .includingGameBlocks(catalog as Map<String, dynamic>, defaultVersion);
  final version = versions.require(defaultVersion);
  final palette = Palette.blocks(
    table,
    version.blockSetAlias,
    gameVersion: defaultVersion,
    includeSupportBlocks: true,
  ).withBlockColors(
    blockColoursFromTexturePalette(
      blockColors as Map<String, dynamic>,
      keep: _keptBlocks(),
    ),
    host: table.colors.first,
  );

  return {for (final entry in palette.entries) entry.blockId};
}

/// The allow-list written by `apply_kept_blocks.dart`, or empty when that has
/// not been run.
Set<String> _keptBlocks() {
  final file = File('assets/colors/kept_blocks.json');
  if (!file.existsSync()) return const {};
  return (jsonDecode(file.readAsStringSync()) as List).cast<String>().toSet();
}
