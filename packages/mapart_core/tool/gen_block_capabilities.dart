import 'dart:convert';
import 'dart:io';

/// Regenerate from the retained game dump and texture extractor metadata.
void main() {
  final game =
      jsonDecode(
            File('tool/data/generated_block_colors.json').readAsStringSync(),
          )
          as Map<String, dynamic>;
  final textures =
      jsonDecode(
            File(
              'assets/colors/texture_palette_26_1_2.json',
            ).readAsStringSync(),
          )
          as Map<String, dynamic>;
  final mapReasons = <String, String>{};
  final textureReasons = <String, String>{};
  final textureStates = <String, String>{};
  final cleanStates = <String>{};
  for (final entry in game.entries) {
    final block = entry.value as Map<String, dynamic>;
    final type = block['class'] as String? ?? '';
    String? reason;
    if (entry.key == 'water' || entry.key == 'lava') {
      reason = '液体需要独立构造，当前不支持';
    } else if (type.contains('Falling') ||
        type.contains('Sand') ||
        type.contains('Gravel') ||
        type.contains('ConcretePowder')) {
      reason = '重力方块需要支撑，当前不支持';
    } else if (block['fullCubeClass'] != true || block['noCollision'] == true) {
      reason = '未确认是可独立放置的完整方块';
    } else if (type.contains('Coral') ||
        type == 'IceBlock' ||
        type.contains('Leaves')) {
      reason = '方块会随环境或更新改变，当前不保证稳定构建';
    }
    if (reason != null) {
      mapReasons[entry.key] = reason;
      textureReasons[entry.key] = reason;
    }
  }
  for (final raw in textures['blocks'] as List<dynamic>) {
    final block = raw as Map<String, dynamic>;
    final id = block['block'] as String;
    if (!game.containsKey(id)) {
      textureReasons[id] = '游戏目录未确认此方块的构建能力';
    }
    final excluded = block['excluded'];
    if (block['srgb'] is List && block['state'] is String) {
      if (excluded == null ||
          (!textureStates.containsKey(id) && !cleanStates.contains(id))) {
        textureStates[id] = block['state'] as String;
      }
      if (excluded == null) cleanStates.add(id);
    }
    if (excluded == 'biomeTinted') {
      textureReasons[id] = '贴图受生物群系取色影响';
    } else if (const {
      'notAFullCube',
      'multipart',
      'noGeometry',
      'translucent',
      'animated',
      'falling',
    }.contains(excluded)) {
      textureReasons[id] = '贴图或形状不适用于稳定的方块像素画';
    }
  }
  File('assets/colors/block_capabilities.json').writeAsStringSync(
    '${const JsonEncoder.withIndent('  ').convert({'schemaVersion': 1, 'source': 'Game constructor metadata and texture extractor exclusions; '
        'generated by tool/gen_block_capabilities.dart', 'mapReasons': mapReasons, 'textureReasons': textureReasons, 'textureStates': textureStates, 'knownBlocks': game.keys.toList()})}\n',
  );
}
